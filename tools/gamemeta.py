#!/usr/bin/env python3
"""Writes rink-rivals/games-meta.js: for every game card on the home page, when it was first added (git) and how big
its code is (a rough measure of how much work went into it). The home page mixes these with popularity to order games."""
import os, re, subprocess, time, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, 'rink-rivals')
idx = open(os.path.join(SITE, 'index.html'), encoding='utf-8').read()
hrefs = sorted(set(re.findall(r'<a class="card" href="([^"#?]+)"', idx)))
def added(path):
    out = subprocess.run(['git', '-C', ROOT, 'log', '--diff-filter=A', '--format=%at', '--', path], capture_output=True, text=True).stdout.split()
    return int(out[-1]) if out else int(time.time())
def code_kb(path):
    if os.path.isdir(path):
        n = 0
        for r, _, fs in os.walk(path):
            for f in fs:
                if f.endswith(('.js', '.html', '.css')): n += os.path.getsize(os.path.join(r, f))
        return n // 1024
    return os.path.getsize(path) // 1024 if os.path.exists(path) else 0
meta = {}
for h in hrefs:
    if h.startswith('oss/'):
        p = os.path.join(SITE, 'oss', h.split('/')[1])
    else:
        p = os.path.join(SITE, h.rstrip('/') + '.html')
    if not os.path.exists(p): continue
    meta[h] = [added(os.path.relpath(p, ROOT)), code_kb(p), 1 if h.startswith('oss/') or h == 'free-games' else 0]
open(os.path.join(SITE, 'games-meta.js'), 'w').write('/* generated by tools/gamemeta.py: [first added (unix time), code size in KB, made elsewhere] */\nwindow.GAMEMETA=' + json.dumps(meta, separators=(',', ':')) + ';\n')
print(len(meta), 'games')
